"""Validate data/catalog.json and write data/catalog.js for the offline index page.

Run from the repository root:  python3 tools/build_catalog.py
"""
import hashlib, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'data', 'catalog.json')
OUT = os.path.join(ROOT, 'data', 'catalog.js')
INDEX = os.path.join(ROOT, 'index.html')


def main():
    cat = json.load(open(SRC, encoding='utf-8'))
    vocab = {t for tags in cat['tag_groups'].values() for t in tags}
    errors, warnings, ids = [], [], set()
    for r in cat['reports']:
        rid = r.get('id', '?')
        for key in ('id', 'title', 'date', 'path', 'summary', 'tags'):
            if not r.get(key):
                errors.append(f'{rid}: missing "{key}"')
        if rid in ids:
            errors.append(f'{rid}: duplicate id')
        ids.add(rid)
        if not re.fullmatch(r'\d{4}-\d{2}-\d{2}', r.get('date', '')):
            errors.append(f'{rid}: date must be YYYY-MM-DD')
        page = os.path.join(ROOT, r.get('path', ''))
        if not os.path.isfile(page):
            errors.append(f'{rid}: page not found: {r.get("path")}')
            html = ''
        else:
            html = open(page, encoding='utf-8').read()
        for f in r.get('files', []):
            if not os.path.exists(os.path.join(ROOT, f['path'])):
                errors.append(f'{rid}: file not found: {f["path"]}')
        all_tags = list(r.get('tags', []))
        for s in r.get('sections', []):
            if html and f'id="{s["anchor"]}"' not in html:
                errors.append(f'{rid}: anchor #{s["anchor"]} not in page')
            all_tags += s.get('tags', [])
        for t in sorted(set(all_tags) - vocab):
            warnings.append(f'{rid}: tag "{t}" is not in tag_groups (shown under 其他)')
    for w in warnings:
        print('warning:', w)
    if errors:
        for e in errors:
            print('error:', e)
        sys.exit(1)
    cat['reports'].sort(key=lambda r: r['date'], reverse=True)
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write('// Generated by tools/build_catalog.py from data/catalog.json. Do not edit by hand.\n')
        fh.write('window.WEST_TW_CATALOG = ')
        json.dump(cat, fh, ensure_ascii=False, indent=1)
        fh.write(';\n')
    # 首頁以內容雜湊作為 catalog.js 的版本參數，避免瀏覽器或 GitHub Pages 快取舊資料
    ver = hashlib.sha1(open(OUT, 'rb').read()).hexdigest()[:10]
    page = open(INDEX, encoding='utf-8').read()
    page = re.sub(r'src="data/catalog\.js(\?v=[0-9a-f]+)?"', f'src="data/catalog.js?v={ver}"', page)
    with open(INDEX, 'w', encoding='utf-8') as fh:
        fh.write(page)
    n_sec = sum(len(r.get('sections', [])) for r in cat['reports'])
    print(f'ok: {len(cat["reports"])} reports, {n_sec} sections -> data/catalog.js')


if __name__ == '__main__':
    main()
